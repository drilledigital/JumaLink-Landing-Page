    <section>
      <h2>Who does this notice apply to?</h2>
      <p>This notice applies to:</p>
      <ul>
        <li>Customers using the JumaLink App or Website to find services.</li>
        <li>Artisans and service providers registering and offering their services on the platform (artisans must be of legal working age).</li>
        <li>Any other individuals interacting with the JumaLink platform.</li>
      </ul>
    </section>

    <section>
      <h2>What Personal Data does JumaLink collect and use?</h2>
      <p>To provide our products and services to you, we may collect, use, store, and otherwise process your Personal Data. The Personal Data requested enables us to deliver the services you subscribe to, verify your identity, and provide full functionality of our platform.</p>
      <p>The Personal Data collected and processed by us may include, where applicable:</p>
      <ul>
        <li><strong>Identity and Contact Data:</strong> Name, email address, phone number, and account credentials.</li>
        <li><strong>Profile Data:</strong> Service portfolios, qualifications, work history, and user reviews (for artisans).</li>
        <li><strong>Usage and Technical Data:</strong> Information on how you interact with our App and Website, general device information, and interaction metrics to improve matching and platform stability.</li>
        <li><strong>Communication Data:</strong> Messages exchanged within the platform's messaging features.</li>
      </ul>
      <p>We only collect the Personal Data that is adequate, relevant, and limited to what is needed in relation to the specific purposes for which we are collecting it.</p>
    </section>

    <section>
      <h2>Where does JumaLink collect my Personal Data from?</h2>
      <p>In most circumstances, we collect Personal Data directly from you when you:</p>
      <ul>
        <li>Register for an account or create a profile on the JumaLink App or Website.</li>
        <li>Use our matching and messaging services.</li>
        <li>Interactions with the App or Website.</li>
        <li>Provide feedback or leave reviews.</li>
        <li>Contact our support team.</li>
      </ul>
      <p>We may also collect technical information automatically as you interact with the app to improve the quality of our services.</p>
    </section>

    <section>
      <h2>For what purposes does JumaLink use your Personal Data?</h2>
      <p>JumaLink may use your Personal Data for the following:</p>
      <ul>
        <li><strong>Service Provision:</strong> To connect customers with artisans, process service requests, and facilitate communication.</li>
        <li><strong>Verification:</strong> To verify your identity when you create an account, purchase products or services, or contact us.</li>
        <li><strong>Platform Improvement:</strong> To analyze general usage trends and optimize our algorithms for better customer-artisan matching.</li>
        <li><strong>Security:</strong> To maintain the integrity and security of our platform and database against unauthorized access or fraudulent activity.</li>
      </ul>
      <p>JumaLink will not further process Personal Data for any purpose that is incompatible with the original purpose unless authorized under the Data Protection Act, 2012 (Act 843), we have your consent, or it is required by law. JumaLink does not share your third party providers but may share your data under legal or regulatory requirements.</p>
    </section>

    <section>
      <h2>Is JumaLink allowed to Process my Personal Data?</h2>
      <p>JumaLink processes your data based on the following legal bases, as appropriate:</p>
      <ul>
        <li><strong>Performance of a Contract:</strong> When processing your data is necessary to perform our obligations to you (e.g., matching you with an artisan).</li>
        <li><strong>Legal Obligation:</strong> When we are required to process your data to comply with legal requirements.</li>
        <li><strong>Legitimate Interests:</strong> Where it is in our legitimate business interest (such as ensuring app security or improving our platform), provided these interests are not overridden by your fundamental rights to data privacy.</li>
        <li><strong>Consent:</strong> Where you have given explicit consent for specific processing activities.</li>
      </ul>
    </section>

    <section>
      <h2>Is it mandatory to provide JumaLink the Personal Data asked for?</h2>
      <p>It is not mandatory for you to provide any Personal Data to us. However, failing to provide certain necessary information may prevent us from providing you with full access to the platform's core features, such as booking services or listing your artisan profile.</p>
    </section>

    <section>
      <h2>How long does JumaLink keep my Personal Data?</h2>
      <p>We will not retain your Personal Data for any longer than is necessary for achieving the purpose(s) for which the Personal Data was collected.</p>
      <p>Once an account is deleted, your data is scheduled for secure deletion. We generally ensure that your data is deleted within 30 days of account closure, unless we are legally required or authorized to retain records for a longer period (e.g., for dispute resolution or compliance with tax and revenue laws).</p>
    </section>

    <section>
      <h2>Does JumaLink transfer my Personal Data to Third Parties?</h2>
      <p>Yes, we may share Personal Data with affiliated third parties, strictly as necessary for our legitimate business needs and to carry out your requests. These include:</p>
      <ul>
        <li><strong>Our Service Providers:</strong> We use secure cloud service providers and infrastructure partners to host our database and platform services. These providers process your data on our behalf under binding agreements with appropriate security safeguards.</li>
        <li><strong>Legal and Regulatory Bodies:</strong> We may disclose data if necessary to comply with applicable laws, court orders, or requests from law enforcement agencies.</li>
      </ul>
      <p>We do not sell your personal data to third-party marketing agencies.</p>
    </section>

    <section>
      <h2>Does JumaLink transfer my Personal Data outside Ghana?</h2>
      <p>Yes, JumaLink may transfer certain Personal Data outside of Ghana. Our secure cloud infrastructure and database hosting services may be located in other regions (such as the US or Europe). When transferring Personal Data internationally, we ensure that adequate data protection safeguards are in place and that the providers adhere to strict data handling requirements consistent with the Data Protection Act, 2012 (Act 843). All data is encrypted in-transit and at rest.</p>
    </section>

    <section>
      <h2>How does JumaLink secure my Personal Data?</h2>
      <p>JumaLink secures the integrity and confidentiality of the Personal Data in its possession by implementing appropriate, reasonable technical, physical, and organizational measures. This prevents:</p>
      <ul>
        <li>Accidental loss of, damage to, or unauthorized destruction of your Personal Data.</li>
        <li>Unlawful or unauthorized access to your Personal Data.</li>
      </ul>
      <p>We continuously assess internal and external risks to our databases and platform endpoints, updating our safeguards to protect against identified vulnerabilities.</p>
    </section>

    <section>
      <h2>How does JumaLink handle Personal Data Breaches?</h2>
      <p>If JumaLink becomes aware of or reasonably suspects a Personal Data Breach has occurred, we will activate our incident management procedures governing the handling and reporting of such breaches. We will notify the Data Protection Commission and the affected data subjects as soon as reasonably practicable, providing sufficient information to allow protective measures to be taken.</p>
    </section>

    <section>
      <h2>What are my rights?</h2>
      <p>Under the Data Protection Act, 2012 (Act 843), you have the right to:</p>
      <ul>
        <li>Access the Personal Data we hold about you.</li>
        <li>Request correction of inaccurate, out-of-date, or incomplete data.</li>
        <li>Request the deletion of your Personal Data.</li>
        <li>Object to the processing of your Personal Data.</li>
        <li>Request that we restrict the processing of your data in certain circumstances.</li>
      </ul>
    </section>

